#!/usr/bin/env python3
"""Independent integer-only IEEE binary32 oracle for Iris sequential FP8 FMA."""
import hashlib
import json
from pathlib import Path
import random

HERE=Path(__file__).resolve().parent

def decode8(raw,e5):
    sign=raw>>7;mbits,bias=(2,15) if e5 else (3,7)
    exponent=(raw&127)>>mbits;fraction=raw&((1<<mbits)-1)
    if e5 and exponent==31:return sign,0,0,'nan' if fraction else 'inf'
    if not e5 and exponent==15 and fraction==7:return sign,0,0,'nan'
    return sign,fraction if exponent==0 else (1<<mbits)+fraction,(1 if exponent==0 else exponent)-bias-mbits,'finite'

def decode32(raw):
    sign=raw>>31;exponent=(raw>>23)&255;fraction=raw&0x7fffff
    if exponent==255:return sign,0,0,'nan' if fraction else 'inf'
    return sign,fraction if not exponent else fraction+(1<<23),(1 if not exponent else exponent)-127-23,'finite'

def round32(integer,quantum,mode,zero_sign=0):
    if integer==0:return zero_sign<<31
    sign=int(integer<0);integer=abs(integer)
    exponent=integer.bit_length()-1+quantum
    target=max(exponent-23,-149)
    shift=target-quantum
    if shift>0:
        kept=integer>>shift;rem=integer-(kept<<shift)
        half=1<<(shift-1)
        increment=(rem>half or (rem==half and kept&1)) if mode==0 else (rem!=0 and sign==1) if mode==2 else (rem!=0 and sign==0) if mode==3 else rem>=half if mode==4 else False
        kept+=bool(increment)
    else:kept=integer<<(-shift)
    if not kept:return sign<<31
    exponent=kept.bit_length()-1+target
    if exponent>127:
        inf=mode in (0,4) or (mode==2 and sign) or (mode==3 and not sign)
        return (sign<<31)|(0x7f800000 if inf else 0x7f7fffff)
    if exponent < -126:return (sign<<31)|(kept<<(target+149))
    width=kept.bit_length()-1
    significand=kept<<(23-width) if width<=23 else kept>>(width-23)
    return (sign<<31)|((exponent+127)<<23)|(significand&0x7fffff)

def fma(a,b,acc,fa,fb,mode):
    sa,ma,ea,ta=decode8(a,fa);sb,mb,eb,tb=decode8(b,fb);sc,mc,ec,tc=decode32(acc)
    sp=sa^sb
    if 'nan' in (ta,tb,tc):return 0x7fc00000
    if (ta=='inf' and tb=='finite' and mb==0) or (tb=='inf' and ta=='finite' and ma==0):return 0x7fc00000
    if ta=='inf' or tb=='inf':
        if tc=='inf' and sc!=sp:return 0x7fc00000
        return (sp<<31)|0x7f800000
    if tc=='inf':return (sc<<31)|0x7f800000
    ep=ea+eb;mp=ma*mb;quantum=min(ep,ec)
    integer=((-1 if sp else 1)*mp<<(ep-quantum))+((-1 if sc else 1)*mc<<(ec-quantum))
    # Exact cancellation uses -0 only for roundTowardNegative; equal-signed
    # zero addends preserve their shared sign, including roundTowardPositive.
    zs=sp if mp==0 and mc==0 and sp==sc else int(mode==2)
    return round32(integer,quantum,mode,zs)

def main():
    rng=random.Random(0x49524953);cases=[]
    seeds=[0,0x80000000,0x3f800000,0x3f800001,0xbf800000,0x4b800000,0xcb800000,0x7f7fffff,0xff7fffff,1,0x007fffff,0x00800000,0x7fc12345,0x7f812345,0x7f800000,0xff800000]
    for fa in (0,1):
      for fb in (0,1):
       for mode in range(5):
        for n in range(512):
          tk=1+n%4;a=[rng.randrange(256) for _ in range(4)];b=[rng.randrange(256) for _ in range(4)]
          if n<256:a[0]=n;b[0]=(n*73+19)&255
          acc=seeds[n%len(seeds)];want=acc
          for k in range(tk):want=fma(a[k],b[k],want,fa,fb,mode)
          cases.append(dict(a=a,b=b,fa=fa,fb=fb,tk=tk,rm=mode,acc=acc,want=want))
        # Sequential-FP32 and upstream bulk-dot deliberately differ here.
        high_a=0x5c if fa else 0x78;high_b=0x5c if fb else 0x78
        a=[high_a,1,high_a|128,0];b=[high_b,1,high_b,0];want=0
        for k in range(3):want=fma(a[k],b[k],want,fa,fb,mode)
        cases.append(dict(a=a,b=b,fa=fa,fb=fb,tk=3,rm=mode,acc=0,want=want))
    header='// Generated by independent integer oracle; no host floating point.\nstruct FP8Case { uint8_t a[4], b[4], fa, fb, tk, rm; uint32_t acc, want; };\nstatic const FP8Case fp8_cases[] = {\n'
    for c in cases:
      a=','.join(hex(x) for x in c['a']);b=','.join(hex(x) for x in c['b'])
      header+=f'  {{{{{a}}},{{{b}}},{c["fa"]},{c["fb"]},{c["tk"]},{c["rm"]},{c["acc"]:#x}u,{c["want"]:#x}u}},\n'
    header+='};\n'
    header+='static const uint32_t fp8_widen[2][256] = {\n'
    for fmt in [0,1]:
      values=[]
      for raw in range(256):
        sign,mant,power,tag=decode8(raw,fmt)
        bits=0x7fc00000 if tag=='nan' else (sign<<31)|0x7f800000 if tag=='inf' else round32((-1 if sign else 1)*mant,power,0,sign)
        values.append(f'{bits:#x}u')
      header+='{'+','.join(values)+'},\n'
    header+='};\n' 
    (HERE/'fp8_cases.hpp').write_text(header)
    (HERE/'fp8-oracle.json').write_text(json.dumps({'oracle':'integer-only FP8 decode and exact fused integer sum rounded to binary32 per K','seed':0x49524953,'cases':len(cases),'formats':['E4M3','E5M2'],'rounding_modes':[0,1,2,3,4],'header_sha256':hashlib.sha256(header.encode()).hexdigest(),'rtl_executed':False},indent=2)+'\n')

if __name__=='__main__':main()
